function sessionFromContextFn(): readonly string[] {
  return [
    'function sessionFromContext(context) {',
    '  if (typeof context !== "string") return "";',
    '  var match = /\\/(\\([A-Za-z0-9()]{0,62}\\))\\/\\$metadata/.exec(context);',
    '  if (!match || typeof match[1] !== "string") return "";',
    '  var segment = match[1];',
    '  return /^[A-Za-z0-9()]{0,64}$/.test(segment) ? segment : "";',
    '}',
  ];
}

